"""Le modèle SQLAlchemy et les migrations Alembic doivent concorder (``alembic check``)."""

from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected

from tests.conftest import Database


def test_models_match_migrations(database: Database) -> None:
    config = Config("alembic.ini")
    config.attributes["url"] = database.owner_url
    try:
        command.check(config)
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - message utile en cas d'échec
        raise AssertionError(f"Migration manquante : {exc}") from None
